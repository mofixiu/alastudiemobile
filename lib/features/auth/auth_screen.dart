                                  'Zara · @zara_demo · zara@demo.alastudie.test\n'
                                  'Ade  · @ade_demo  · ade@demo.alastudie.test\n'
                                  'Maya · @maya_demo · maya@demo.alastudie.test\n'
                                  'Sam  · @sam_demo · sam@demo.alastudie.test\n\n'
                                  'Password for all: DemoStudy8!',
                                  style: TextStyle(
                                    height: 1.6,
                                    fontWeight: FontWeight.w700,
                                  ),
                                ),
                              )
                            : const SizedBox.shrink(),
                      ),
                    ],
                  ),
                ),
              ),
            ),
          ],
        ],
      ],
    ),
  );

  String get _actionLabel => switch (_mode) {
    AuthMode.login => 'Find your room',
    AuthMode.signup => 'Create account',
    AuthMode.verify => 'Verify email',
    AuthMode.forgot => 'Send reset code',
    AuthMode.reset => 'Save new password',
    AuthMode.mailbox => 'Open mailbox',
  };

  Widget _mailbox(AppController app) => Column(
    crossAxisAlignment: CrossAxisAlignment.start,
    children: [
      Eyebrow('Development only'),
      const SizedBox(height: 10),
      Text('Local mailbox', style: Theme.of(context).textTheme.headlineLarge),
      const SizedBox(height: 6),
      Text(_email.text, style: TextStyle(color: context.appMuted)),
      const SizedBox(height: 16),
      if (app.localEmails.isEmpty)
        const EmptyNotice(
          title: 'No messages yet',
          body:
              'Create an account or request a reset to generate a local email.',
          icon: Icons.mark_email_unread_outlined,
        )
      else
        for (final message in app.localEmails)
          SoftPanel(
            color: context.appSurface,
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Eyebrow('${message['subject'] ?? 'Local email'}'),
                const SizedBox(height: 8),
                SelectableText(
                  '${message['body'] ?? ''}',
                  style: const TextStyle(fontSize: 13, height: 1.45),
                ),
                const SizedBox(height: 8),
                TextButton.icon(
                  onPressed: () {
                    final body = '${message['body']}';
                    final match = RegExp(
                      r'code is:\s*([\w-]+)',
                    ).firstMatch(body);
                    if (match != null) {
                      _code.text = match.group(1)!;
                      setState(
                        () => _mode = body.toLowerCase().contains('verify')
                            ? AuthMode.verify
                            : AuthMode.reset,
                      );
                    }
                  },
                  icon: const AppIcon(Icons.content_paste_go_rounded),
                  label: const Text('Use code'),
                ),
              ],
            ),
          ),
      const SizedBox(height: 16),
      TextButton(
        onPressed: () => setState(() => _mode = AuthMode.login),
        child: const Text('Back'),
      ),
    ],
  );

  Widget _field(
    String label,
    TextEditingController controller, {
    required String hint,
    required IconData icon,
    String? Function(String?)? validator,
    TextInputType? keyboard,
    bool obscure = false,
    VoidCallback? toggleObscure,
  }) => Padding(
    padding: const EdgeInsets.only(bottom: 13),
    child: Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        Eyebrow(label),
        const SizedBox(height: 7),
        TextFormField(
          controller: controller,
          validator: validator,
          keyboardType: keyboard,
          obscureText: obscure,
          decoration: InputDecoration(
            hintText: hint,
            prefixIcon: AppIcon(icon, size: 19),
            suffixIcon: toggleObscure == null
                ? null
                : IconButton(
                    onPressed: toggleObscure,
                    icon: AppIcon(
                      obscure
                          ? Icons.visibility_outlined
                          : Icons.visibility_off_outlined,
                    ),
                  ),
          ),
        ),
      ],
    ),
  );

  String? _notEmpty(String? value) =>
      value == null || value.trim().isEmpty ? 'Enter a username.' : null;
  String? _validLoginIdentifier(String? value) =>
      value == null || value.trim().isEmpty
      ? 'Enter your email or username.'
      : null;
  String? _validEmail(String? value) =>
      value == null || !value.contains('@') || !value.contains('.')
      ? 'Enter a valid email address.'
      : null;
  String? _validPassword(String? value) =>
      value == null || value.length < (_mode == AuthMode.login ? 1 : 8)
      ? _mode == AuthMode.login
            ? 'Enter your password.'
            : 'Use at least 8 characters.'
      : null;
}
