            ],
          ),
          const SizedBox(height: 13),
          if (_mode == AuthMode.signup) ...[
            _field(
              'USERNAME',
              _username,
              hint: 'e.g. mofiyine',
              icon: Icons.alternate_email_rounded,
              validator: _notEmpty,
