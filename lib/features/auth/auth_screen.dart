import '../app/app_controller.dart';

enum AuthMode { login, signup, verify, forgot, reset, mailbox }

class AuthScreen extends StatefulWidget {
  const AuthScreen({super.key});
  @override
  State<AuthScreen> createState() => _AuthScreenState();
}

class _AuthScreenState extends State<AuthScreen> {
  final _form = GlobalKey<FormState>();
  final _email = TextEditingController();
  final _username = TextEditingController();
  final _password = TextEditingController();
  final _code = TextEditingController();
  AuthMode _mode = AuthMode.login;
  bool _ageConfirmed = false;
  bool _obscure = true;
  bool _showDemoAccounts = false;

  @override
  void dispose() {
    _email.dispose();
    _username.dispose();
    _password.dispose();
    _code.dispose();
    super.dispose();
  }

  Future<void> _submit(AppController app) async {
    if (_mode != AuthMode.mailbox && !(_form.currentState?.validate() ?? false))
      return;
    switch (_mode) {
      case AuthMode.login:
        await app.login(_email.text, _password.text);
        break;
      case AuthMode.signup:
        if (!_ageConfirmed) {
          showAppMessage(context, 'Confirm that you are 18 or older.');
          return;
        }
        await app.register(
          email: _email.text,
          username: _username.text,
          password: _password.text,
          ageConfirmed: _ageConfirmed,
        );
        if (app.errorMessage == null) setState(() => _mode = AuthMode.verify);
        break;
      case AuthMode.verify:
        await app.verifyEmail(_email.text, _code.text);
        if (app.errorMessage == null) setState(() => _mode = AuthMode.login);
        break;
      case AuthMode.forgot:
        await app.forgotPassword(_email.text);
        if (app.errorMessage == null) setState(() => _mode = AuthMode.reset);
        break;
      case AuthMode.reset:
        await app.resetPassword(_email.text, _code.text, _password.text);
        if (app.errorMessage == null) setState(() => _mode = AuthMode.login);
        break;
      case AuthMode.mailbox:
        break;
    }
    if (app.statusMessage != null) showAppMessage(context, app.statusMessage);
    if (app.errorMessage != null) showAppMessage(context, app.errorMessage);
  }

  String get _title => switch (_mode) {
    AuthMode.login => 'Make room\nfor focus.',
    AuthMode.signup => 'Start a\nstudy habit.',
    AuthMode.verify => 'One quick\ncheck-in.',
    AuthMode.forgot => 'Get back\nin the room.',
    AuthMode.reset => 'A fresh\nstart.',
    AuthMode.mailbox => 'Local\nmailbox.',
  };

  String get _subtitle => switch (_mode) {
    AuthMode.login => 'Find your people. Get into the work.',
    AuthMode.signup => 'Create an account for your next good study session.',
    AuthMode.verify =>
      'Open the local mailbox and paste your verification code.',
    AuthMode.forgot =>
      'We’ll save a reset code in your local development mailbox.',
    AuthMode.reset => 'Choose a new password to get back to your work.',
    AuthMode.mailbox =>
      'Messages generated by this local app stay on this device.',
  };

