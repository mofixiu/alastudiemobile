                  ? 'you@university.edu or username'
                  : 'you@university.edu',
              icon: _mode == AuthMode.login
                  ? Icons.alternate_email_rounded
                  : Icons.mail_outline_rounded,
              keyboard: _mode == AuthMode.login
                  ? TextInputType.emailAddress
                  : TextInputType.emailAddress,
              validator: _mode == AuthMode.login
                  ? _validLoginIdentifier
                  : _validEmail,
            ),
